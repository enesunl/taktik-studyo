// Explicit local-only SQL/RLS verification. Every test row is rolled back.
import {execFileSync} from 'node:child_process';
import {randomUUID} from 'node:crypto';
import {emptyWeeklyXI,pickWeeklyPlayer} from '../src/lib/weekly-xi.js';
const container='supabase_db_taktik-studyo';
const inspect=JSON.parse(execFileSync('docker',['inspect','--format','{{json .NetworkSettings.Ports}}',container],{encoding:'utf8',windowsHide:true}));
if(!inspect['5432/tcp']?.some(p=>p.HostPort==='54322'))throw Error('Refusing unverified local database target');
const a=randomUUID(),b=randomUUID(),id=randomUUID(),second=randomUUID(),third=randomUUID();
const snapshot=pickWeeklyPlayer(emptyWeeklyXI(),1,{id:randomUUID(),teamId:'galatasaray',name:'Local test player',teamName:'Galatasaray',number:10,positionGroup:'M',specificPosition:'CM',color:'#a61931',color2:'#f5bd28'});
const quote=v=>"'"+String(v).replaceAll("'","''")+"'";
const insert=(pid,owner=a,week=8)=>`insert into public.weekly_lineups(id,user_id,title,season,week,formation,snapshot) values('${pid}','${owner}','Local verification','2026/27',${week},'4-3-3',${quote(JSON.stringify(snapshot))});`;
const sql=`create function pg_temp.assert(ok boolean,label text) returns void language plpgsql as $$begin if ok is distinct from true then raise exception 'Failed: %',label; end if; end$$;
begin;
select pg_temp.assert((select relrowsecurity from pg_class where oid='public.weekly_lineups'::regclass),'RLS enabled');
select pg_temp.assert((select count(*)=4 from pg_policies where schemaname='public' and tablename='weekly_lineups'),'four policies');
select pg_temp.assert(not has_table_privilege('anon','public.weekly_lineups','SELECT'),'no anon SELECT grant');
select pg_temp.assert(not has_column_privilege('authenticated','public.weekly_lineups','revision','UPDATE'),'revision immutable');
insert into auth.users(id) values('${a}'),('${b}');
set local role authenticated;
select set_config('request.jwt.claim.sub','${a}',true);
${insert(id)}${insert(second)}${insert(third,a,9)}
select pg_temp.assert((select count(*)=3 from public.weekly_lineups),'A sees three records, two in same week');
select pg_temp.assert((select snapshot=${quote(JSON.stringify(snapshot))}::jsonb from public.weekly_lineups where id='${id}'),'snapshot roundtrip');
update public.weekly_lineups set title='Renamed',week=null,snapshot=${quote(JSON.stringify(snapshot))} where id='${id}' and revision=1;
select pg_temp.assert((select revision=2 and week is null and title='Renamed' from public.weekly_lineups where id='${id}'),'update, rename, unassigned week, revision');
select set_config('request.jwt.claim.sub','${b}',true);
select pg_temp.assert((select count(*)=0 from public.weekly_lineups),'B cannot SELECT A');
with changed as(update public.weekly_lineups set title='Forbidden' returning id) select pg_temp.assert((select count(*)=0 from changed),'B cannot UPDATE A');
with removed as(delete from public.weekly_lineups returning id) select pg_temp.assert((select count(*)=0 from removed),'B cannot DELETE A');
do $$begin ${insert(randomUUID())} raise exception 'Forged owner INSERT allowed'; exception when insufficient_privilege then null; end$$;
reset role;
set local role anon;
do $$begin perform * from public.weekly_lineups; raise exception 'Anon SELECT allowed'; exception when insufficient_privilege then null; end$$;
do $$begin ${insert(randomUUID())} raise exception 'Anon INSERT allowed'; exception when insufficient_privilege then null; end$$;
reset role;
set local role authenticated;
select set_config('request.jwt.claim.sub','${a}',true);
with removed as(delete from public.weekly_lineups where id='${id}' returning id) select pg_temp.assert((select count(*)=1 from removed),'A deletes own record');
reset role;
rollback;
select pg_temp.assert(not exists(select 1 from auth.users where id in ('${a}','${b}')),'test accounts rolled back');
`;
execFileSync('docker',['exec','-i',container,'psql','-U','postgres','-d','postgres','-q','-v','ON_ERROR_STOP=1'],{input:sql,encoding:'utf8',windowsHide:true,stdio:['pipe','pipe','pipe']});
console.log('PASS: Taktik Studyo local Postgres; migration/RLS, A CRUD, B isolation, anon denial, same-week multiple saves, snapshot roundtrip, revision. Test rows/accounts rolled back.');
